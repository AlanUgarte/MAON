// Exporta filas a un CSV descargable — Excel lo abre nativo, no hace falta sumar
// una librería xlsx solo para esto. Sin dependencias del carrito/filtro: recibe las
// filas ya filtradas por quien llama.
export function exportCsv(filename: string, headers: string[], rows: (string | number)[][]) {
  const escape = (v: string | number) => {
    const s = String(v);
    return /[",\n;]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  const lines = [headers, ...rows].map((row) => row.map(escape).join(';'));
  // BOM al inicio: sin esto Excel en Windows abre acentos/ñ como caracteres corruptos.
  const csv = '﻿' + lines.join('\r\n');
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename.endsWith('.csv') ? filename : `${filename}.csv`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
